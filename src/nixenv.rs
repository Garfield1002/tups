//! Nix environment integration — hermetic (roadmap slice 7, pieces 1–3).
//!
//! The project's environment *is* a flake. `tup run --env nix <project>` (and `tup up --env
//! nix`) evaluates the project's flake to a single profile store path (a `buildEnv`) and makes
//! that profile the **only** source of userland: the host `/usr` is dropped, PATH is just
//! `<profile>/bin`, and the host environment is wiped. The closure already lives in the shared
//! read-only `/nix/store` bind, so realising the env copies nothing into the container.
//!
//! The flake is the single source of truth, read by one evaluator (Nix):
//!   * **piece 2 — prologues.** The env is composed from named, reusable profiles: a generic
//!     `base` every project inherits, plus opt-in language prologues (`rust`, `python`, …).
//!     The selection lives in `active.nix` and the registry in `prologues.nix` (both tup-owned
//!     data the stable `flake.nix` imports), so `tup env add/rm` never rewrites the flake.
//!   * **piece 3 — `outputs.tup`.** The one thing a flake doesn't model — network + host binds
//!     ("links") — lives as plain data in the flake's `tup` output, which tup reads with
//!     `nix eval` and applies.

use crate::net::Net;
use crate::project::{ensure_project_root, project_dir};
use crate::sandbox::Bind;
use std::ffi::OsString;
use std::path::{Path, PathBuf};
use std::process::{exit, Command};

#[derive(Clone, Copy, PartialEq, Eq)]
pub(crate) enum EnvMode {
    /// Inherit the host's `/usr` + `/etc` (the original behaviour).
    Host,
    /// Hermetic: the environment is the project's flake; host `/usr` is dropped.
    Nix,
}

impl EnvMode {
    pub(crate) fn label(self) -> &'static str {
        match self {
            EnvMode::Host => "host",
            EnvMode::Nix => "nix",
        }
    }
}

pub(crate) fn env_mode_from_str(s: Option<&str>) -> EnvMode {
    match s {
        Some("nix") => EnvMode::Nix,
        Some("host") => EnvMode::Host,
        other => {
            eprintln!(
                "tup: unknown --env {:?} (want host|nix)",
                other.unwrap_or("")
            );
            exit(2);
        }
    }
}

/// The flake output `tup` builds for the container's userland.
const ENV_OUTPUT: &str = "tupEnv";

/// The named prologues: a reusable profile of tools/libs. `base` is always active; the rest
/// are language prologues a project opts into. Sharing across projects is automatic via the
/// store's content-addressed dedup — no shared flake needed.
const PROLOGUES: &[(&str, &[&str])] = &[
    (
        "base",
        &[
            "bashInteractive",
            "coreutils",
            "cacert",
            "gitMinimal",
            "ripgrep",
            "curl",
            "findutils",
            "gnugrep",
            "gnused",
            "gawk",
            "which",
        ],
    ),
    ("rust", &["rustc", "cargo", "rust-analyzer", "gcc", "pkg-config"]),
    ("python", &["python3", "uv", "ruff"]),
    ("node", &["nodejs", "pnpm"]),
    ("go", &["go", "gopls"]),
    ("c", &["gcc", "gnumake", "pkg-config"]),
    ("lean", &["lean4"]),
];

fn is_prologue(name: &str) -> bool {
    PROLOGUES.iter().any(|(n, _)| *n == name)
}

/// The stable flake: generated once, then the user's to edit. It imports the two tup-owned
/// data files (`active.nix`, `prologues.nix`) and carries the `tup` plain-data output.
const FLAKE: &str = r#"{
  # Generated by tup. The prologue selection lives in ./active.nix and the registry in
  # ./prologues.nix (both tup-managed); `extraPackages` and the `tup` output are yours to edit.
  description = "tup project environment";
  inputs.nixpkgs.url = "nixpkgs";
  outputs = { self, nixpkgs }:
    let
      system = "x86_64-linux";
      pkgs = nixpkgs.legacyPackages.${system};
      prologues = import ./prologues.nix { inherit pkgs; };
      active = import ./active.nix;
      extraPackages = with pkgs; [ ];
    in {
      packages.${system}.tupEnv = pkgs.buildEnv {
        name = "tup-env";
        paths = (pkgs.lib.concatMap (n: prologues.${n}) active) ++ extraPackages;
      };
      # Plain data tup reads via `nix eval`: network mode + host binds ("links").
      tup = {
        net = "pasta";
        binds = [
          # { host = "/abs/host/path"; path = "/abs/container/path"; ro = true; }
        ];
      };
    };
}
"#;

pub(crate) fn env_dir(project: &str) -> PathBuf {
    project_dir(project).join("env")
}

/// The synthesized `/etc` for the hermetic root (passwd/group/resolv.conf live here).
pub(crate) fn etc_dir(project: &str) -> PathBuf {
    env_dir(project).join("etc")
}

/// `<profile>/etc/ssl/certs/ca-bundle.crt` — the CA bundle from the flake's `cacert`.
pub(crate) fn ca_bundle(profile: &Path) -> PathBuf {
    profile.join("etc/ssl/certs/ca-bundle.crt")
}

/// The default inner command for an env mode when the user gave none.
pub(crate) fn default_shell(env: EnvMode) -> Vec<OsString> {
    match env {
        // Resolved via PATH = <profile>/bin inside the hermetic root.
        EnvMode::Nix => vec![OsString::from("bash")],
        EnvMode::Host => vec![OsString::from("/bin/bash")],
    }
}

/// Render `prologues.nix` from the registry: `{ pkgs }: with pkgs; { base = [ … ]; … }`.
fn render_prologues_nix() -> String {
    let mut s = String::from("{ pkgs }:\nwith pkgs; {\n");
    for (name, pkgs) in PROLOGUES {
        s.push_str(&format!("  {name} = [ {} ];\n", pkgs.join(" ")));
    }
    s.push_str("}\n");
    s
}

/// Serialize an active-prologue selection as a Nix list for `active.nix`.
fn render_active_nix(active: &[String]) -> String {
    let items: Vec<String> = active.iter().map(|n| format!("\"{n}\"")).collect();
    format!("[ {} ]\n", items.join(" "))
}

/// Parse the quoted tokens out of `active.nix` (a tup-written `[ "a" "b" ]`).
fn parse_active_nix(text: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut in_tok = false;
    let mut cur = String::new();
    for c in text.chars() {
        if c == '"' {
            if in_tok {
                out.push(std::mem::take(&mut cur));
            }
            in_tok = !in_tok;
        } else if in_tok {
            cur.push(c);
        }
    }
    out
}

/// Create the env scaffolding under `~/.tup/<project>/env/`: the registry (always refreshed),
/// the selection (defaulting to `[ "base" ]`), the flake (once), and the synthesized `/etc`.
fn scaffold(project: &str) {
    let dir = env_dir(project);
    if let Err(e) = std::fs::create_dir_all(&dir) {
        eprintln!("tup: create {}: {e}", dir.display());
        exit(1);
    }
    // Registry: pure, tup-owned — safe to rewrite every time so new prologues propagate.
    let _ = std::fs::write(dir.join("prologues.nix"), render_prologues_nix());
    // Selection: tup-owned, but preserve the user's choices across runs.
    let active = dir.join("active.nix");
    if !active.exists() {
        let _ = std::fs::write(&active, render_active_nix(&["base".to_string()]));
    }
    // Flake: generated once, then the user's to edit.
    let flake = dir.join("flake.nix");
    if !flake.exists() {
        if let Err(e) = std::fs::write(&flake, FLAKE) {
            eprintln!("tup: write {}: {e}", flake.display());
            exit(1);
        }
        eprintln!("[tup] wrote env flake: {}", flake.display());
    }
    ensure_etc(project);
}

/// Read the active prologue selection (`base` guaranteed present).
pub(crate) fn read_active(project: &str) -> Vec<String> {
    let text = std::fs::read_to_string(env_dir(project).join("active.nix")).unwrap_or_default();
    let mut v = parse_active_nix(&text);
    if !v.iter().any(|n| n == "base") {
        v.insert(0, "base".to_string());
    }
    v
}

/// Host side: ensure the scaffolding exists, build the flake, and return the realised profile
/// store path. Exits with a message on any failure.
pub(crate) fn realize(project: &str) -> PathBuf {
    scaffold(project);
    let dir = env_dir(project);
    let link = dir.join("profile");
    eprintln!("[tup] realising env: nix build .#{ENV_OUTPUT} …");
    let status = Command::new("nix")
        .args([
            "build",
            "--extra-experimental-features",
            "nix-command flakes",
            "--out-link",
        ])
        .arg(&link)
        .arg(format!("{}#{ENV_OUTPUT}", dir.display()))
        .status();
    match status {
        Ok(s) if s.success() => {}
        Ok(s) => {
            eprintln!("tup: nix build failed (exit {})", s.code().unwrap_or(-1));
            exit(1);
        }
        Err(e) => {
            eprintln!("tup: could not run `nix` ({e}). --env nix needs nix on PATH.");
            exit(1);
        }
    }
    match std::fs::canonicalize(&link) {
        Ok(p) => p,
        Err(e) => {
            eprintln!("tup: resolve profile {}: {e}", link.display());
            exit(1);
        }
    }
}

/// Synthesize a minimal `/etc` for the hermetic root: an account for the mapped root uid and a
/// resolver. For `Net::Pasta` the sandbox binds its own resolv.conf over this one.
pub(crate) fn ensure_etc(project: &str) {
    let etc = etc_dir(project);
    if let Err(e) = std::fs::create_dir_all(&etc) {
        eprintln!("tup: create {}: {e}", etc.display());
        exit(1);
    }
    let _ = std::fs::write(
        etc.join("passwd"),
        "root:x:0:0:root:/work:/bin/sh\nnobody:x:65534:65534:nobody:/:/bin/sh\n",
    );
    let _ = std::fs::write(etc.join("group"), "root:x:0:\nnogroup:x:65534:\n");
    // Mirror the host resolver (useful for --net host); fall back to a public resolver.
    let resolv = std::fs::read_to_string("/etc/resolv.conf").unwrap_or_default();
    let resolv = if resolv.trim().is_empty() {
        "nameserver 1.1.1.1\n".to_string()
    } else {
        resolv
    };
    let _ = std::fs::write(etc.join("resolv.conf"), resolv);
}

// ---------------------------------------------------------------------------
// Piece 3: the `tup` flake output (plain data) — network + host binds.
// ---------------------------------------------------------------------------

/// What the flake's `tup` output declares. Empty when the flake has no such output.
pub(crate) struct TupConfig {
    pub net: Option<Net>,
    pub binds: Vec<Bind>,
}

/// Read and apply the flake's `tup` output (`nix eval --apply`, so no JSON dependency). A
/// missing or malformed `tup` output yields an empty config rather than an error.
pub(crate) fn read_tup_config(project: &str) -> TupConfig {
    let flakeref = env_dir(project).display().to_string();
    let net = nix_eval_tup(&flakeref, r#"c: c.net or """#).and_then(|s| match s.trim() {
        "pasta" => Some(Net::Pasta),
        "host" => Some(Net::Host),
        "none" => Some(Net::None),
        _ => None,
    });
    // One tab-separated line per bind: "<ro|rw>\t<host>\t<path>".
    let apply = r#"c: builtins.concatStringsSep "\n" (map (b: "${if (b.ro or true) then "ro" else "rw"}\t${b.host}\t${b.path}") (c.binds or []))"#;
    let mut binds = Vec::new();
    if let Some(out) = nix_eval_tup(&flakeref, apply) {
        for line in out.lines().filter(|l| !l.trim().is_empty()) {
            let p: Vec<&str> = line.splitn(3, '\t').collect();
            if p.len() == 3 {
                binds.push(Bind {
                    src: PathBuf::from(p[1]),
                    dst: PathBuf::from(p[2]),
                    ro: p[0] == "ro",
                });
            }
        }
    }
    TupConfig { net, binds }
}

fn nix_eval_tup(flakeref: &str, apply: &str) -> Option<String> {
    let out = Command::new("nix")
        .args([
            "eval",
            "--raw",
            "--extra-experimental-features",
            "nix-command flakes",
        ])
        .arg(format!("{flakeref}#tup"))
        .arg("--apply")
        .arg(apply)
        .output()
        .ok()?;
    if out.status.success() {
        Some(String::from_utf8_lossy(&out.stdout).into_owned())
    } else {
        None
    }
}

// ---------------------------------------------------------------------------
// `tup env` — inspect and edit the prologue selection.
// ---------------------------------------------------------------------------

pub(crate) fn cmd_env(args: &[String]) {
    let project = match args.first() {
        Some(p) => p.clone(),
        None => {
            eprintln!("usage: tup env <project> [list | add <name>... | rm <name>...]");
            exit(2);
        }
    };
    ensure_project_root(&project); // validate name + ensure state dir
    scaffold(&project);

    match args.get(1).map(String::as_str) {
        None => show(&project),
        Some("list") => {
            println!("available prologues:");
            for (n, pkgs) in PROLOGUES {
                println!("  {n:<8} {}", pkgs.join(" "));
            }
        }
        Some("add") => edit(&project, &args[2..], true),
        Some("rm") => edit(&project, &args[2..], false),
        Some(other) => {
            eprintln!("tup env: unknown subcommand '{other}' (want list|add|rm)");
            exit(2);
        }
    }
}

fn show(project: &str) {
    let active = read_active(project);
    println!("project {project}");
    println!("  active prologues: {}", active.join(" "));
    let cfg = read_tup_config(project);
    if let Some(n) = cfg.net {
        println!("  tup.net:   {}", n.label());
    }
    if !cfg.binds.is_empty() {
        println!("  tup.binds:");
        for b in &cfg.binds {
            println!(
                "    {} {} -> {}",
                if b.ro { "ro" } else { "rw" },
                b.src.display(),
                b.dst.display()
            );
        }
    }
    println!("  (edit {}#tup for net/binds)", env_dir(project).join("flake.nix").display());
}

fn edit(project: &str, names: &[String], add: bool) {
    if names.is_empty() {
        eprintln!("tup env: {} needs a prologue name", if add { "add" } else { "rm" });
        exit(2);
    }
    for n in names {
        if !is_prologue(n) {
            eprintln!("tup env: unknown prologue '{n}' (try `tup env {project} list`)");
            exit(2);
        }
        if !add && n == "base" {
            eprintln!("tup env: 'base' is always active and cannot be removed");
            exit(2);
        }
    }
    let mut active = read_active(project);
    for n in names {
        if add {
            if !active.iter().any(|a| a == n) {
                active.push(n.clone());
            }
        } else {
            active.retain(|a| a != n);
        }
    }
    let _ = std::fs::write(env_dir(project).join("active.nix"), render_active_nix(&active));
    println!("active prologues: {}", active.join(" "));
    println!("(run `tup run --env nix {project}` to rebuild)");
}
