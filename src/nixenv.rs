/// What the flake's `tup` output declares. Empty when the flake has no such output.
pub(crate) struct TupConfig {
    pub net: Option<Net>,
    pub persist: Vec<PathBuf>,
    pub binds: Vec<Bind>,
    /// `agents.ssh.key`: the tup-managed deploy key whose ssh-agent should be forwarded.
    pub ssh_agent_key: Option<String>,
}

/// Read and apply the flake's `tup` output (`nix eval --apply`, so no JSON dependency). A
/// flake with no `tup` output yields an empty config; a `tup` output that *exists but fails to
/// evaluate* is a hard error (see the probe below) rather than a silent empty config.
pub(crate) fn read_tup_config(project: &str) -> TupConfig {
    let flakeref = env_dir(project).display().to_string();
    let empty = TupConfig {
        net: None,
        persist: Vec::new(),
        binds: Vec::new(),
        ssh_agent_key: None,
    };
    // Probe whether the flake has a `tup` output at all. Distinguish two failures that used to
    // collapse together: a flake that simply has no `tup` output (normal — e.g. host-authored)
    // returns empty silently; but a `tup` output that exists and *throws* (or nix erroring for
    // any other reason) must NOT be treated as "no config" — that would silently drop declared
    // persist volumes (writes to them would land in the ephemeral root and be lost). Fail loudly.
    if let Err(e) = nix_eval_tup(&flakeref, r#"c: """#) {
        if e.contains("does not provide attribute") {
            return empty; // no `tup` output — legitimately nothing to apply
        }
        eprintln!(
            "[tup] error: the flake's `tup` output could not be evaluated; refusing to continue \
             so declared persist volumes/binds aren't silently dropped:\n  {}",
            nix_error_summary(&e)
        );
        exit(1);
    }
    // `net`/`persist` use `or` defaults, so they only fail on a genuinely broken value.
    let net = nix_eval_tup(&flakeref, r#"c: c.net or """#)
        .ok()
        .and_then(|s| match s.trim() {
            "pasta" => Some(Net::Pasta),
            "host" => Some(Net::Host),
            "none" => Some(Net::None),
            _ => None,
        });
    // Persist volumes: one container path per line.
    let persist = match nix_eval_tup(
        &flakeref,
        r#"c: builtins.concatStringsSep "\n" (c.persist or [])"#,
    ) {
        Ok(s) => s
            .lines()
            .filter(|l| !l.trim().is_empty())
            .map(PathBuf::from)
            .collect(),
        Err(e) => {
            warn_tup("persist", &e);
            Vec::new()
        }
    };
    // One tab-separated line per bind: "<ro|rw>\t<host>\t<path>". A single malformed entry
    // (missing host/path) throws here; we warn and skip the whole set rather than silently
    // leaving the container without binds it was told to have.
    let apply = r#"c: builtins.concatStringsSep "\n" (map (b: "${if (b.ro or true) then "ro" else "rw"}\t${b.host}\t${b.path}") (c.binds or []))"#;
    let binds = match nix_eval_tup(&flakeref, apply) {
        Ok(out) => {
            let mut v = Vec::new();
            for line in out.lines().filter(|l| !l.trim().is_empty()) {
                let p: Vec<&str> = line.splitn(3, '\t').collect();
                if p.len() == 3 {
                    v.push(Bind {
                        src: PathBuf::from(p[1]),
                        dst: PathBuf::from(p[2]),
                        ro: p[0] == "ro",
                    });
                }
            }
            v
        }
        Err(e) => {
            warn_tup("binds", &e);
            Vec::new()
        }
    };
    // agents.ssh.key — the deploy key whose agent to forward. `or ""` catches a missing
    // agents/ssh/key at any level; a genuinely broken value warns (like persist/binds).
    let ssh_agent_key = match nix_eval_tup(&flakeref, r#"c: c.agents.ssh.key or """#) {
        Ok(s) => {
            let s = s.trim().to_string();
            if s.is_empty() {
                None
            } else {
                Some(s)
            }
        }
        Err(e) => {
            warn_tup("agents.ssh.key", &e);
            None
        }
    };
    TupConfig {
        net,
        persist,
        binds,
        ssh_agent_key,
    }
}

/// Read the project's `gates.git` policy, if declared. `None` when there is no gate (no
/// `gates.git.remote`) — the remote is the required, container-unspecifiable target.
pub(crate) fn read_gate(project: &str) -> Option<GatePolicy> {
    let flakeref = env_dir(project).display().to_string();
    let remote = nix_eval_tup(&flakeref, r#"c: c.gates.git.remote or """#)
        .ok()?
        .trim()
        .to_string();
    if remote.is_empty() {
        return None;
    }
    let list = |apply: &str| -> Vec<String> {
        nix_eval_tup(&flakeref, apply)
            .map(|s| {
                s.lines()
                    .filter(|l| !l.trim().is_empty())
                    .map(|l| l.trim().to_string())
                    .collect()
            })
            .unwrap_or_default()
    };
    Some(GatePolicy {
        remote,
        allow: list(r#"c: builtins.concatStringsSep "\n" (c.gates.git.allow or [])"#),
        refs: list(r#"c: builtins.concatStringsSep "\n" (c.gates.git.refs or [])"#),
    })
}

/// Evaluate `apply` against the flake's `tup` output. `Ok` on success, `Err(stderr)` when the
/// eval fails (a missing `tup` output, or a mistake in the user's `tup` data).
fn nix_eval_tup(flakeref: &str, apply: &str) -> Result<String, String> {
    let out = Command::new("nix")
        .args([
            "eval",
            "--raw",
            "--extra-experimental-features",
            "nix-command flakes",
        ])
        .arg(format!("{flakeref}#tup"))
        .arg("--apply")
        .arg(apply)
        .output()
        .map_err(|e| e.to_string())?;
    if out.status.success() {
        Ok(String::from_utf8_lossy(&out.stdout).into_owned())
    } else {
        Err(String::from_utf8_lossy(&out.stderr).into_owned())
    }
}

/// The concrete cause from a nix error cascade: the last `error:` line with text after the
/// colon (e.g. "attribute 'path' missing"), which is the useful one to show a user.
fn nix_error_summary(err: &str) -> &str {
    err.lines()
        .filter_map(|l| l.trim().strip_prefix("error:"))
        .map(str::trim)
        .rfind(|m| !m.is_empty())
        .unwrap_or("eval failed (see nix output)")
}

/// Warn that one `outputs.tup` field was ignored because its eval threw — surfacing the nix
/// error's key line so a typo in the user's `tup` data isn't swallowed silently.
fn warn_tup(attr: &str, err: &str) {
    let msg = nix_error_summary(err);
    eprintln!("[tup] warning: ignoring outputs.tup.{attr} — {msg}");
}

